"""Shared trajectory analysis for predictions and MOT Ground Truth."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import asdict, dataclass, replace
from typing import Any

from people_flow.config import CountingSettings, RoiSettings
from people_flow.counting.dwell_time import DwellTimeRecord
from people_flow.counting.geometry import DirectedLine, LineSide, PolygonRegion
from people_flow.counting.line_counter import LineCounter, LineCrossingEvent
from people_flow.counting.roi_counter import RoiCounter, RoiFrameSnapshot
from people_flow.datasets.mot_ground_truth import (
    GroundTruthPolicy,
    MotGroundTruth,
    ground_truth_track_records,
)
from people_flow.errors import EvaluationError
from people_flow.evaluation.counting_metrics import (
    CountingEvaluationMetrics,
    compute_counting_metrics,
)
from people_flow.tracking.track_record import TrackRecord


@dataclass(frozen=True, slots=True)
class TrajectoryAnalysis:
    """Events, occupancy, and dwell generated by the shared counters."""

    events: tuple[LineCrossingEvent, ...]
    occupancy: tuple[RoiFrameSnapshot, ...]
    dwell_records: tuple[DwellTimeRecord, ...]
    processed_frames: int

    @property
    def occupancy_values(self) -> tuple[int, ...] | None:
        """Return per-frame occupancy, or None when ROI analysis is disabled."""

        if not self.occupancy:
            return None
        return tuple(snapshot.occupancy for snapshot in self.occupancy)


@dataclass(frozen=True, slots=True)
class MotPredictionEvaluation:
    """Complete shared-algorithm comparison for one MOT sequence."""

    sequence_name: str
    frame_rate: float
    frame_count: int
    ground_truth_track_records: int
    predicted_track_records: int
    ground_truth: TrajectoryAnalysis
    predicted: TrajectoryAnalysis
    metrics: CountingEvaluationMetrics
    ground_truth_policy: GroundTruthPolicy

    def as_dict(self) -> dict[str, Any]:
        """Return an auditable JSON mapping without embedding every trajectory row."""

        return {
            "ground_truth_available": True,
            "sequence_name": self.sequence_name,
            "frame_rate": self.frame_rate,
            "frame_count": self.frame_count,
            "ground_truth_track_records": self.ground_truth_track_records,
            "predicted_track_records": self.predicted_track_records,
            "ground_truth_event_count": len(self.ground_truth.events),
            "predicted_event_count": len(self.predicted.events),
            "ground_truth_policy": asdict(self.ground_truth_policy),
            **self.metrics.as_dict(),
        }


def analyze_trajectories(
    records: Sequence[TrackRecord],
    *,
    frame_count: int,
    frame_rate: float,
    counting: CountingSettings,
    roi: RoiSettings,
) -> TrajectoryAnalysis:
    """Run the production LineCounter and RoiCounter over an ordered trajectory stream."""

    if frame_count <= 0 or frame_rate <= 0:
        raise EvaluationError("frame_count and frame_rate must be positive")
    grouped: dict[int, list[TrackRecord]] = {}
    for record in records:
        if not 1 <= record.frame_id <= frame_count:
            raise EvaluationError(
                f"Track frame {record.frame_id} is outside the evaluation range 1..{frame_count}"
            )
        if record.class_id != 0:
            raise EvaluationError(
                f"Trajectory analysis only accepts person class 0, got {record.class_id}"
            )
        grouped.setdefault(record.frame_id, []).append(record)

    line_counter = _line_counter(counting)
    roi_counter = _roi_counter(roi)
    events: list[LineCrossingEvent] = []
    occupancy: list[RoiFrameSnapshot] = []
    for frame_id in range(1, frame_count + 1):
        timestamp_ms = (frame_id - 1) * 1000.0 / frame_rate
        frame_records = [
            replace(record, timestamp_ms=timestamp_ms) for record in grouped.get(frame_id, ())
        ]
        if line_counter is not None:
            events.extend(line_counter.process_frame(frame_records, frame_id=frame_id))
        if roi_counter is not None:
            occupancy.append(
                roi_counter.process_frame(
                    frame_records,
                    frame_id=frame_id,
                    timestamp_ms=timestamp_ms,
                )
            )
    dwell_records = roi_counter.dwell_records() if roi_counter is not None else ()
    return TrajectoryAnalysis(tuple(events), tuple(occupancy), dwell_records, frame_count)


def evaluate_mot_prediction(
    ground_truth: MotGroundTruth,
    predicted_records: Sequence[TrackRecord],
    *,
    counting: CountingSettings,
    roi: RoiSettings,
    ground_truth_policy: GroundTruthPolicy | None = None,
) -> MotPredictionEvaluation:
    """Compare MOT Ground Truth and predictions through the exact same counters."""

    effective_policy = ground_truth_policy or GroundTruthPolicy()
    truth_records = ground_truth_track_records(ground_truth, policy=effective_policy)
    truth_analysis = analyze_trajectories(
        truth_records,
        frame_count=ground_truth.sequence.sequence_length,
        frame_rate=ground_truth.sequence.frame_rate,
        counting=counting,
        roi=roi,
    )
    predicted_analysis = analyze_trajectories(
        predicted_records,
        frame_count=ground_truth.sequence.sequence_length,
        frame_rate=ground_truth.sequence.frame_rate,
        counting=counting,
        roi=roi,
    )
    metrics = compute_counting_metrics(
        truth_analysis.events,
        predicted_analysis.events,
        ground_truth_occupancy=truth_analysis.occupancy_values,
        predicted_occupancy=predicted_analysis.occupancy_values,
    )
    return MotPredictionEvaluation(
        sequence_name=ground_truth.sequence.name,
        frame_rate=ground_truth.sequence.frame_rate,
        frame_count=ground_truth.sequence.sequence_length,
        ground_truth_track_records=len(truth_records),
        predicted_track_records=len(predicted_records),
        ground_truth=truth_analysis,
        predicted=predicted_analysis,
        metrics=metrics,
        ground_truth_policy=effective_policy,
    )


def _line_counter(settings: CountingSettings) -> LineCounter | None:
    if not settings.enabled:
        return None
    if settings.line is None:
        raise EvaluationError("Counting is enabled without line geometry")
    return LineCounter(
        DirectedLine(
            settings.line.p1,
            settings.line.p2,
            enter_side=LineSide(settings.line.enter_side),
        ),
        min_track_age=settings.min_track_age,
        min_displacement_pixels=settings.min_displacement_pixels,
        cooldown_frames=settings.cooldown_frames,
        max_track_gap_frames=settings.max_track_gap_frames,
    )


def _roi_counter(settings: RoiSettings) -> RoiCounter | None:
    if not settings.enabled:
        return None
    return RoiCounter(
        PolygonRegion(settings.name, settings.points),
        max_track_gap_frames=settings.max_track_gap_frames,
    )
